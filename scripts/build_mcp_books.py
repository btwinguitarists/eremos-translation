#!/usr/bin/env python3
"""Write mcp/src/books.js: every book's USFM code, names (English, Thai long/short/abbr),
OSIS id, repo slug and chapter count, plus a lookup of the names people type
("John", "Jn", "JHN", "ยอห์น", "ยน"). Run after book names change:
    python3 scripts/build_mcp_books.py
"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from export_projection import BOOKS as CANON          # (slug, English, OSIS)
from export_to_usfm import BOOKS as USFM               # code -> (slug, long_th, short_th, abbr_th, mt, en)

bundle = json.loads((ROOT / "output" / "bundle" / "eremos-thai.json").read_text(encoding="utf-8"))
chapters = {b["usfm"]: len(b["chapters"]) for b in bundle["books"]}
slug_to_code = {v[0]: c for c, v in USFM.items()}
EXTRA = {  # common English abbreviations beyond the automatic ones
    "PSA": ["ps", "psalm", "pss"], "SNG": ["song", "song of solomon", "songs", "sos", "canticles"],
    "PHP": ["phil", "php"], "PHM": ["philem", "phm"], "JHN": ["jn", "jhn"], "JDG": ["jdg", "judg"],
    "EZK": ["ezek", "ezk"], "MRK": ["mk", "mrk"], "MAT": ["mt", "matt"], "LUK": ["lk"], "JAS": ["jas", "jm"],
    "REV": ["rev", "revelation", "revelations", "apocalypse"], "ECC": ["eccl", "qoheleth"], "LAM": ["lam"],
    "DEU": ["deut", "dt"], "NUM": ["num", "nm"], "EXO": ["ex", "exod"], "GEN": ["gn"], "LEV": ["lv"],
    "JOS": ["josh"], "RUT": ["ru"], "OBA": ["obad"], "NAM": ["nah"], "ZEP": ["zeph"], "ZEC": ["zech"],
    "MAL": ["mal"], "HAB": ["hab"], "HAG": ["hag"], "ACT": ["acts"], "ROM": ["rom", "rm"], "GAL": ["gal"],
    "EPH": ["eph"], "COL": ["col"], "TIT": ["tit"], "HEB": ["heb"], "JUD": ["jude", "jud"],
}
books, alias = [], {}
def add(k, code):
    k = re.sub(r"[\s.]+", "", k.lower())
    if k: alias.setdefault(k, code)
for slug, en, osis in CANON:
    code = slug_to_code[slug]; _, long_th, short_th, abbr_th, _mt, _en = USFM[code]
    books.append({"usfm": code, "osis": osis, "slug": slug, "name_en": en, "name_th": long_th,
                  "short_th": short_th, "abbr_th": abbr_th, "chapters": chapters[code]})
    for k in [code, osis, en, slug, long_th, short_th, abbr_th, *EXTRA.get(code, [])]:
        add(k, code)
    m = re.match(r"^([123]) (.+)$", en)            # "1 Corinthians" -> 1cor, 1co, i corinthians
    if m:
        n, rest = m.groups()
        for k in (rest[:2], rest[:3], rest[:4]):
            add(n + k, code)
        add({"1": "i", "2": "ii", "3": "iii"}[n] + rest, code)
    else:
        for k in (en[:3], en[:4]):
            alias.setdefault(re.sub(r"\s", "", k.lower()), code)
out = ("// Generated by scripts/build_mcp_books.py. Do not edit by hand.\n"
       f"export const BOOKS = {json.dumps(books, ensure_ascii=False, indent=1)};\n"
       f"export const ALIAS = {json.dumps(alias, ensure_ascii=False, indent=0, sort_keys=True)};\n")
(ROOT / "mcp" / "src" / "books.js").write_text(out, encoding="utf-8")
print(f"{len(books)} books, {len(alias)} names → mcp/src/books.js")
